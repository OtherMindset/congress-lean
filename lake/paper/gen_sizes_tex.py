#!/usr/bin/env python3
"""Write Table 5 (certificate sizes and build costs) from supplementary/table_sizes.json.

Usage: python3 -I gen_sizes_tex.py <table_sizes.json> <out.tex>
table_sizes.json is produced by table_sizes.py (tables, slices, recurrence degree), the #eval of the seed and step
product sizes with the library's own explore (Sizes.lean), and the artifact's build_report.csv.
"""
import json
import statistics as st
import sys

t = json.load(open(sys.argv[1]))
inst = [v for v in t if not v['group']]
grp = [v for v in t if v['group']]


def n(x):
    return f'{x:,}'.replace(',', '{,}')


def chunks(v):
    return len(v.get('slices', [])) if v['chunked'] else 1


L = [r'\begin{table}[htb]',
     r'\caption{Certificate sizes and build costs for the ' + str(len(t)) + r' tables of the artifact. $Q$: states of the '
     "table; seed, step: reachable product states of the seed and step checks, recomputed with the library's own "
     r'exploration (for the chunked checks they equal the total of the chunks); chunks: pieces of the step check; deg: '
     r'degree of the recurrence polynomial; core, step: build time of the module with the table, seed check and '
     r'counting check, and of the modules with the step-check chunks (for unchunked checks the step check is in the '
     r'core module); peak: largest peak memory of these modules and the theorem module. Times are from the artifact '
     r'build of Table~\ref{tab:build}, not the runner.}\label{tab:sizes}',
     r'\centering\small',
     r'\begin{tabular}{@{}rrrrrrrrr@{}}', r'\toprule',
     r'$R$ & $Q$ & seed & step & chunks & deg & core (s) & step (s) & peak (MB)\\', r'\midrule']
for v in sorted(inst, key=lambda v: v['R']):
    step_t = f"{v['t_step']:.1f}" if v['chunked'] else '--'
    L.append(f"{v['R']} & {v['Q']} & {v['seed']} & {n(v['step'])} & {chunks(v)} & {v['deg']} & {v['t_core']:.1f} & "
             f"{step_t} & {n(v['mem'])}\\\\")
L.append(r'\midrule')
gfiles = sorted({v['core_mod'] for v in grp})


def med(xs):
    m = st.median(xs)
    return n(int(m)) if m == int(m) else f'{m:.1f}'


L.append(r'\multicolumn{9}{@{}l}{The other ' + str(len(grp)) + r' tables, in ' + str(len(gfiles)) +
         r' group files (unchunked, deg 3):}\\')
for lab, f in (('median', med), ('max', lambda xs: n(max(xs)))):
    L.append(f"{lab} & {f([v['Q'] for v in grp])} & {f([v['seed'] for v in grp])} & {f([v['step'] for v in grp])} & 1 & 3 & "
             r'\multicolumn{3}{l}{' + ('' if lab == 'median' else
                                      f"group file: {max(v['t_core'] for v in grp):.1f}\\,s, {n(max(v['mem'] for v in grp))}\\,MB")
             + r'}\\')
L.append(r'\midrule')
for lab, f in (('all, median', med), ('all, max', lambda xs: n(max(xs)))):
    L.append(f"\\multicolumn{{1}}{{@{{}}l}}{{{lab}}} & {f([v['Q'] for v in t])} & {f([v['seed'] for v in t])} & "
             f"{f([v['step'] for v in t])} & & & & & \\\\")
L += [r'\bottomrule', r'\end{tabular}', r'\end{table}']
open(sys.argv[2], 'w').write('% generated by gen_sizes_tex.py from supplementary/table_sizes.json\n' + '\n'.join(L) + '\n')
