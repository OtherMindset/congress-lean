#!/usr/bin/env python3
"""Generate the paper's artifact-derived LaTeX from the consolidated Lake project (congress-lean, lake/).

Usage: python3 -I gen_artifact_tex.py <lake_dir> <rows.json> <statement_check.txt> <out_dir>
Writes: defs_listing.tex (LT2D/Defs.lean verbatim), build_table.tex (build by directory),
        appendix_statements.tex (Appendix A).
"""
import csv
import glob
import hashlib
import json
import os
import re
import sys
from collections import defaultdict

lake, rows_path, check_path, out = sys.argv[1:5]
man = json.load(open(os.path.join(lake, 'manifest.json')))
rows = json.load(open(rows_path))['rows']
thms = {t['name']: t for t in man['top_level_theorems']}
mod_sha = {m['module']: m['file_sha256'] for m in man['modules']}
mod_path = {m['module']: m['path'] for m in man['modules']}
status = {}
for line in open(check_path):
    m = re.match(r'(MATCH|MISMATCH|UNTEMPLATED|READ)\s+(\S+)', line)
    if m:
        status[m[2]] = m[1]
assert len(status) == len(thms) and not any(s in ('MISMATCH', 'UNTEMPLATED') for s in status.values()), status


def tt(s, dots=False):
    """Lean text -> LaTeX \\texttt. Line breaks are allowed after '=', '→', ',', '∧', '↔', and after '+', '-', '*'
    outside parentheses (Unicode is handled by newunicodechar in main.tex)."""
    s = ' '.join(s.split())
    marks, depth = [], 0
    for i, c in enumerate(s):
        depth += (c == '(') - (c == ')')
        nxt = s[i + 1:i + 2]
        if nxt == ' ' and (c in '=→,∧↔' or (c in '+-*' and depth == 0)):
            marks.append(i + 1)
    rep = {'\\': r'\textbackslash{}', '_': r'\_', '{': r'\{', '}': r'\}', '#': r'\#', '%': r'\%', '&': r'\&',
           '^': r'\textasciicircum{}', '~': r'\textasciitilde{}', '$': r'\$', ' ': '~'}
    out = []
    for i, c in enumerate(s):
        if i in marks:
            out.append('\\ \\allowbreak{}')
            continue
        out.append(rep.get(c, c))
        if c == '.' and dots:
            out.append('\\allowbreak{}')
    return r'\texttt{' + ''.join(out) + '}'


def name(n):
    return tt(n.removeprefix('LT2D.'), dots=True)


# ---- 1. Defs listing -------------------------------------------------------------------------------------
defs = open(os.path.join(lake, 'LT2D/Defs.lean'), 'rb').read()
with open(os.path.join(out, 'defs_listing.tex'), 'w') as f:
    f.write('% generated by gen_artifact_tex.py from lake/LT2D/Defs.lean, SHA-256 '
            + hashlib.sha256(defs).hexdigest() + '\n')
    f.write('\\begin{Verbatim}[fontsize=\\footnotesize,frame=single,framesep=2mm,breaklines=true,breakanywhere=false,curlyquotes=true,'
            'breaksymbolleft=\\tiny\\ensuremath{\\hookrightarrow}]\n')
    f.write(defs.decode().rstrip('\n') + '\n')
    f.write('\\end{Verbatim}\n')

# ---- 2. Build by directory -------------------------------------------------------------------------------
order = ['Defs+Basic', 'VN', 'A272706', 'Early', 'Groups', 'Instances', 'LDR', 'Relations', 'R750', 'All']
label = {'Defs+Basic': r'\texttt{Defs}, \texttt{Basic}', 'All': r'\texttt{All}'}
G = defaultdict(lambda: {'mods': 0, 'lines': 0, 'sec': 0.0, 'max': 0.0, 'rss': 0})
for r in csv.DictReader(open(os.path.join(lake, 'build_report.csv'))):
    mod = r['module']
    assert r['exit'] == '0'
    path = 'All.lean' if mod == 'All' else mod.replace('.', '/') + '.lean'
    g = ('Defs+Basic' if mod in ('LT2D.Defs', 'LT2D.Basic') else 'All' if mod == 'All' else mod.split('.')[1])
    d = G[g]
    d['mods'] += 1
    d['lines'] += open(os.path.join(lake, path), 'rb').read().count(b'\n')
    s = float(r['seconds'])
    d['sec'] += s
    d['max'] = max(d['max'], s)
    d['rss'] = max(d['rss'], int(r['peak_rss_mb']))
assert set(G) == set(order)


def fmt(x):
    return f'{x:,}'.replace(',', '{,}')


with open(os.path.join(out, 'build_table.tex'), 'w') as f:
    f.write('% generated by gen_artifact_tex.py from lake/build_report.csv\n')
    f.write('\\begin{table}[htb]\n\\caption{Build of the artifact by directory: one module at a time in import order on 2 vCPUs and 7.8\\,GB, Mathlib from its cache. Lines are newline characters; time is the sum over modules; peak is the largest peak resident memory of a module.}\\label{tab:build}\n\\centering\\small\n\\begin{tabular}{@{}lrrrrr@{}}\n\\toprule\ndirectory & modules & lines & time (s) & slowest (s) & peak (MB)\\\\\n\\midrule\n')
    for g in order:
        d = G[g]
        f.write(f"{label.get(g, chr(92) + 'texttt{' + g + '}')} & {d['mods']} & {fmt(d['lines'])} & "
                f"{fmt(round(d['sec']))} & {d['max']:.1f} & {fmt(d['rss'])}\\\\\n")
    T = {k: sum(G[g][k] for g in order) for k in ('mods', 'lines', 'sec')}
    f.write('\\midrule\n')
    f.write(f"total & {T['mods']} & {fmt(T['lines'])} & {fmt(round(T['sec']))} & "
            f"{max(G[g]['max'] for g in order):.1f} & {fmt(max(G[g]['rss'] for g in order))}\\\\\n")
    f.write('\\bottomrule\n\\end{tabular}\n\\end{table}\n')

# ---- 3. Appendix A ---------------------------------------------------------------------------------------
used = set()
A = []
A.append('% generated by gen_artifact_tex.py from lake/manifest.json (runner statements) and the statement check')
A.append(r'Each statement below is printed as the runner elaborated it; the consolidated build prints the same text '
         r"for all 191 (Section~\ref{sec:check}). The column ``check'' is the result of the mechanical check: \emph{m} for "
         r'matched with its template and the printed claim, \emph{r} for statements to be read. Statements are '
         r'grouped by the table or theorem they prove. The modules and their SHA-256 hashes, as files of the '
         r'artifact, are listed at the end.')


def table(title, items, cols='statement', w=(3.6, 7.1)):
    A.append(r'\subsection*{' + title + '}')
    A.append(r'\begin{small}\begin{longtable}{@{}>{\raggedright}p{' + str(w[0]) + r'cm}>{\raggedright}p{0.9cm}'
             r'>{\raggedright\arraybackslash}p{' + str(w[1]) + 'cm}@{}}')
    A.append(r'\toprule theorem & check & ' + cols + r'\\ \midrule\endhead')
    for n, text in items:
        used.add(n)
        A.append(f"{name(n)} & {'m' if status[n] == 'MATCH' else 'r'} & {text}\\\\[2pt]")
    A.append(r'\bottomrule\end{longtable}\end{small}')


form = [r['theorem'] for r in rows if r['table'] == 'formulas']
table('Closed forms (Table~\\ref{tab:formulas})', [(n, tt(thms[n]['runner_statement'])) for n in form])

eq = []
for r in rows:
    if r['table'] == 'equal':
        for o, n in zip(r['others'], r['theorems']):
            s = ' '.join(thms[n]['runner_statement'].split())
            tmpl = f'∀ (n : ℕ), LT2D.onCount {o} (2 ^ n - 1) = LT2D.onCount {r["rule"]} (2 ^ n - 1)'
            eq.append((n, f'$S={o}$, $R={r["rule"]}$' if s == tmpl else tt(s)))
A.append(r'\subsection*{Equal counts (Table~\ref{tab:equal})}')
A.append(r'Except where a statement is printed, each theorem below states, verbatim, '
         + tt('∀ (n : ℕ), LT2D.onCount S (2 ^ n - 1) = LT2D.onCount R (2 ^ n - 1)') + ' for the $S$ and $R$ given.')
table('', eq, 'statement or $(S,R)$', (5.2, 5.5))
A[-4] = A[-4].replace(r'\subsection*{}', '')

rel = [t.strip() for r in rows if r['table'] == 'relations' for t in r['theorem'].split(',')]
table('Relations (Table~\\ref{tab:relations})', [(n, tt(thms[n]['runner_statement'])) for n in rel])
a006 = re.search(r'^def a006095.*$', open(os.path.join(lake, 'LT2D/Relations/NT2_M.lean')).read(), re.M)[0]
A.append(r'The theorem \lean{a270218\_eq\_four\_a006095} uses the function defined in '
         r'\texttt{LT2D/Relations/NT2\_M.lean},' + '\n' + r'\begin{quote}' + tt(a006) + r'\end{quote}'
         + '\n' + r'\noindent with natural-number subtraction and division.')

main_order = ['LT2D.a169707_rule750', 'LT2D.rule750_on_in_window', 'LT2D.r469_parity', 'LT2D.r337_parity',
              'LT2D.count_compl558', 'LT2D.r337_count_odd', 'LT2D.a273331_a16', 'LT2D.r990_caState_eq_926',
              'LT2D.r990_count']
where = {'LT2D.a169707_rule750': 'Thm.~\\ref{thm:r750}', 'LT2D.rule750_on_in_window': 'Thm.~\\ref{thm:r750}',
         'LT2D.r469_parity': 'Thm.~\\ref{thm:parity}', 'LT2D.r337_parity': 'Thm.~\\ref{thm:parity}',
         'LT2D.count_compl558': 'Thm.~\\ref{thm:parity}', 'LT2D.r337_count_odd': 'Thm.~\\ref{thm:parity}',
         'LT2D.a273331_a16': 'Sect.~\\ref{sec:terms}', 'LT2D.r990_caState_eq_926': 'Sect.~\\ref{sec:example926}',
         'LT2D.r990_count': 'Sect.~\\ref{sec:example926}'}
assert set(main_order) == set(thms) - used, set(thms) - used - set(main_order)
table('Theorems of the main text', [(n, '(' + where[n] + ') ' + tt(thms[n]['runner_statement'])) for n in main_order])
assert used == set(thms)

mods = sorted({t['module'] for t in thms.values()})
A.append(r'\subsection*{Modules holding top-level theorems}')
A.append(r'Paths are relative to \texttt{lake/}; the hash is the SHA-256 of the file in the artifact.')
A.append(r'\begin{scriptsize}\begin{longtable}{@{}l@{}}\toprule path and SHA-256\\ \midrule\endhead')
for m in mods:
    A.append(r'\texttt{' + mod_path[m].replace('_', r'\_') + r'}\\*' + '\n' + r'\quad\texttt{' + mod_sha[m] + r'}\\[1pt]')
A.append(r'\bottomrule\end{longtable}\end{scriptsize}')
open(os.path.join(out, 'appendix_statements.tex'), 'w').write('\n'.join(A) + '\n')
print('theorems', len(used), 'modules', len(mods), 'groups', {g: G[g]['mods'] for g in order})
